class LabelSmoothingCrossEntropy(nn.Module):
    def __init__(self, smoothing: float = 0.1, weight: torch.Tensor = None):
        super().__init__()
        self.smoothing = smoothing
        self.weight = weight
        
    def forward(self, pred: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
        n_classes = pred.size(1)
        smooth_labels = torch.full_like(pred, self.smoothing / (n_classes - 1))
        smooth_labels.scatter_(1, target.unsqueeze(1), 1 - self.smoothing)
        log_probs = F.log_softmax(pred, dim=1)
        
        if self.weight is not None:
            weight = self.weight.to(pred.device)
            sample_weights = weight[target]
            loss = -(smooth_labels * log_probs).sum(dim=1)
            loss = (loss * sample_weights).mean()
        else:
            loss = -(smooth_labels * log_probs).sum(dim=1).mean()
        return loss


class FocalLoss(nn.Module):
    def __init__(self, alpha: float = 1.0, gamma: float = 2.0, 
                 weight: torch.Tensor = None, reduction: str = 'mean'):
        super().__init__()
        self.alpha = alpha
        self.gamma = gamma
        self.weight = weight
        self.reduction = reduction
    
    def forward(self, inputs: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        weight = self.weight.to(inputs.device) if self.weight is not None else None
        ce_loss = F.cross_entropy(inputs, targets, weight=weight, reduction='none')
        pt = torch.exp(-ce_loss)
        focal_weight = (1 - pt) ** self.gamma
        focal_loss = self.alpha * focal_weight * ce_loss
        
        if self.reduction == 'mean':
            return focal_loss.mean()
        return focal_loss


class SupConLoss(nn.Module):
    """Supervised Contrastive Loss."""
    def __init__(self, temperature: float = 0.07):
        super().__init__()
        self.temperature = temperature
    
    def forward(self, features: torch.Tensor, labels: torch.Tensor) -> torch.Tensor:
        device = features.device
        batch_size = features.size(0)
        
        # Cast to float32 for numerical stability
        features = features.float()
        features = F.normalize(features, dim=1)
        similarity_matrix = torch.matmul(features, features.T) / self.temperature
        
        labels = labels.contiguous().view(-1, 1)
        mask = torch.eq(labels, labels.T).float().to(device)
        
        logits_mask = torch.ones_like(mask) - torch.eye(batch_size, device=device)
        mask = mask * logits_mask
        
        exp_logits = torch.exp(similarity_matrix) * logits_mask
        log_prob = similarity_matrix - torch.log(exp_logits.sum(dim=1, keepdim=True) + 1e-8)
        
        mask_pos_pairs = torch.clamp(mask.sum(dim=1), min=1)
        mean_log_prob_pos = (mask * log_prob).sum(dim=1) / mask_pos_pairs
        
        return -mean_log_prob_pos.mean()


