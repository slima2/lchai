class ConvStem(nn.Module):
    """CTransPath's ConvStem patch embedding."""
    def __init__(self, img_size=224, patch_size=4, in_chans=3, embed_dim=96):
        super().__init__()
        stem_dim1 = embed_dim // 8
        stem_dim2 = embed_dim // 4
        
        self.proj = nn.Sequential(
            nn.Conv2d(in_chans, stem_dim1, kernel_size=3, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(stem_dim1), nn.GELU(),
            nn.Conv2d(stem_dim1, stem_dim2, kernel_size=3, stride=2, padding=1, bias=False),
            nn.BatchNorm2d(stem_dim2), nn.GELU(),
            nn.Conv2d(stem_dim2, embed_dim, kernel_size=1, stride=1, padding=0, bias=False),
            nn.BatchNorm2d(embed_dim),
        )
        self.norm = nn.LayerNorm(embed_dim)
    
    def forward(self, x):
        x = self.proj(x)
        x = x.permute(0, 2, 3, 1)
        return self.norm(x)


class CTransPathBackbone(nn.Module):
    """CTransPath backbone."""
    def __init__(self, checkpoint_path: str = None, freeze_layers: int = 0):
        super().__init__()
        if not HAS_TIMM:
            raise ImportError("timm required")
        
        self.model = timm.create_model('swin_tiny_patch4_window7_224', pretrained=False, num_classes=0)
        self.model.patch_embed = ConvStem(img_size=224, patch_size=4, in_chans=3, embed_dim=96)
        self.out_features = self.model.num_features
        
        if checkpoint_path and os.path.exists(checkpoint_path):
            self._load_checkpoint(checkpoint_path)
            print(f"  ✓ Loaded CTransPath checkpoint")
        
        if freeze_layers > 0:
            for i, layer in enumerate(self.model.layers):
                if i < freeze_layers:
                    for param in layer.parameters():
                        param.requires_grad = False
    
    def _load_checkpoint(self, checkpoint_path: str):
        checkpoint = torch.load(checkpoint_path, map_location='cpu', weights_only=False)
        state_dict = checkpoint.get('model', checkpoint.get('state_dict', checkpoint)) if isinstance(checkpoint, dict) else checkpoint
        
        remapped = {}
        for key, value in state_dict.items():
            if key.startswith('head.') or key.startswith('fc.') or 'attn_mask' in key or 'relative_position_index' in key:
                continue
            new_key = key
            if '.downsample.' in key:
                for i in range(3):
                    if f'layers.{i}.downsample.' in key:
                        new_key = key.replace(f'layers.{i}.downsample.', f'layers.{i+1}.downsample.')
                        break
            remapped[new_key] = value
        
        model_state = self.model.state_dict()
        filtered = {k: v for k, v in remapped.items() if k in model_state and v.shape == model_state[k].shape}
        if len(filtered) >= 150:
            self.model.load_state_dict(filtered, strict=False)
    
    def forward(self, x):
        return self.model(x)


