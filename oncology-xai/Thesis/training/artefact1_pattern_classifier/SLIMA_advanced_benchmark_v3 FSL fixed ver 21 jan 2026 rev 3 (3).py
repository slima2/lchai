def run_single_experiment(loss_type: str, backbone_type: str,
                          train_loader, val_loader, test_loader,
                          num_classes: int, class_counts: List[int],
                          id2label: Dict, device: str = 'cuda',
                          epochs: int = 150, verbose: bool = True,
                          ce_weight: torch.Tensor = None,
                          use_mixup: bool = True, mixup_prob: float = 0.3,
                          use_cutmix: bool = True, cutmix_prob: float = 0.3,
                          checkpoint_path: str = None, 
                          hf_token: str = None, local_dir: str = None,
                          use_amp: bool = True,
                          **loss_kwargs) -> Dict:
    
    experiment_name = f"{loss_type}_{backbone_type}"
    
    if verbose:
        print(f"\n{'='*60}")
        print(f"Training: {experiment_name.upper()}")
        print(f"{'='*60}")
        sys.stdout.flush()
    
    # Clear GPU memory before starting
    clear_gpu_memory()
    
    model, loss_fn = build_model_with_loss(
        loss_type, backbone_type, num_classes, config.EMBED_DIM,
        checkpoint_path, config.FREEZE_BACKBONE_LAYERS,
        class_counts, device, ce_weight=ce_weight, total_epochs=epochs,
        hf_token=hf_token, local_dir=local_dir, **loss_kwargs
    )
    
    model = model.to(device)
    loss_fn = loss_fn.to(device)
    
    # NO DataParallel to avoid NCCL errors
    # Using single GPU is more stable
    
    backbone_params = model[0].parameters()
    head_params = model[1].parameters()
    
    optimizer = torch.optim.AdamW([
        {'params': backbone_params, 'lr': config.LR_BACKBONE},
        {'params': head_params, 'lr': config.LR},
        {'params': loss_fn.parameters(), 'lr': config.LR},
    ], weight_decay=config.WEIGHT_DECAY)
    
    def lr_lambda(epoch):
        if epoch < config.WARMUP_EPOCHS:
            return epoch / config.WARMUP_EPOCHS
        return 0.5 * (1 + math.cos(math.pi * (epoch - config.WARMUP_EPOCHS) / (epochs - config.WARMUP_EPOCHS)))
    
    scheduler = torch.optim.lr_scheduler.LambdaLR(optimizer, lr_lambda)
    scaler = torch.cuda.amp.GradScaler() if (device == 'cuda' and use_amp) else None
    
    best_val_f1 = 0
    best_epoch = 0
    best_state = None
    
    for epoch in range(epochs):
        if hasattr(loss_fn, 'set_epoch'):
            loss_fn.set_epoch(epoch)
        
        model.train()
        loss_fn.train()
        total_loss = 0
        
        for images, labels in train_loader:
            images, labels = images.to(device), labels.to(device)
            
            use_mix = False
            if use_mixup and random.random() < mixup_prob:
                images, labels_a, labels_b, lam = mixup_data(images, labels, alpha=config.MIXUP_ALPHA)
                use_mix = True
            elif use_cutmix and random.random() < cutmix_prob:
                images, labels_a, labels_b, lam = cutmix_data(images, labels)
                use_mix = True
            
            optimizer.zero_grad()
            
            if scaler is not None:
                with torch.cuda.amp.autocast():
                    features = model(images)
                    # Cast features to float32 for loss computation
                    features = features.float()
                    if use_mix:
                        loss1, logits = loss_fn(features, labels_a)
                        loss2, _ = loss_fn(features, labels_b)
                        loss = lam * loss1 + (1 - lam) * loss2
                    else:
                        loss, logits = loss_fn(features, labels)
                
                scaler.scale(loss).backward()
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
                torch.nn.utils.clip_grad_norm_(loss_fn.parameters(), max_norm=1.0)
                scaler.step(optimizer)
                scaler.update()
            else:
                features = model(images)
                if use_mix:
                    loss1, logits = loss_fn(features, labels_a)
                    loss2, _ = loss_fn(features, labels_b)
                    loss = lam * loss1 + (1 - lam) * loss2
                else:
                    loss, logits = loss_fn(features, labels)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
                optimizer.step()
            
            total_loss += loss.item()
        
        train_loss = total_loss / len(train_loader)
        
        # Validation
        model.eval()
        loss_fn.eval()
        val_preds, val_labels_list = [], []
        
        with torch.no_grad():
            for images, labels in val_loader:
                images, labels = images.to(device), labels.to(device)
                features = model(images).float()
                
                if hasattr(loss_fn, 'weight'):
                    weight = loss_fn.weight
                elif hasattr(loss_fn, 'head') and hasattr(loss_fn.head, 'weight'):
                    weight = loss_fn.head.weight
                elif hasattr(loss_fn, 'head1'):
                    weight = loss_fn.head1.weight
                else:
                    weight = loss_fn.head.weight
                
                weight = weight.float()
                
                if weight.dim() == 3:
                    weight_norm = F.normalize(weight, dim=2)
                    features_norm = F.normalize(features, dim=1)
                    cosine_all = torch.einsum('bd,ckd->bck', features_norm, weight_norm)
                    logits, _ = cosine_all.max(dim=2)
                else:
                    weight_norm = F.normalize(weight, dim=1)
                    features_norm = F.normalize(features, dim=1)
                    logits = features_norm @ weight_norm.t()
                
                val_preds.extend(logits.argmax(dim=1).cpu().numpy())
                val_labels_list.extend(labels.cpu().numpy())
        
        val_f1 = f1_score(np.array(val_labels_list), np.array(val_preds), average='macro')
        
        if val_f1 > best_val_f1:
            best_val_f1 = val_f1
            best_epoch = epoch
            model_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
            best_state = {'model': model_state, 'loss_fn': {k: v.cpu().clone() for k, v in loss_fn.state_dict().items()}}
        
        if verbose and (epoch + 1) % config.PRINT_FREQ == 0:
            print(f"  Ep {epoch+1:3d}/{epochs} | Loss {train_loss:.4f} | Val-F1 {val_f1:.4f} | Best {best_val_f1:.4f}@{best_epoch+1}")
            sys.stdout.flush()
        
        scheduler.step()
    
    # Load best model
    if best_state:
        model.load_state_dict({k: v.to(device) for k, v in best_state['model'].items()})
        loss_fn.load_state_dict({k: v.to(device) for k, v in best_state['loss_fn'].items()})
    
    # Test evaluation
    model.eval()
    test_preds, test_labels_list = [], []
    
    with torch.no_grad():
        for images, labels in test_loader:
            images, labels = images.to(device), labels.to(device)
            features = model(images).float()
            
            if hasattr(loss_fn, 'weight'):
                weight = loss_fn.weight
            elif hasattr(loss_fn, 'head') and hasattr(loss_fn.head, 'weight'):
                weight = loss_fn.head.weight
            elif hasattr(loss_fn, 'head1'):
                weight = loss_fn.head1.weight
            else:
                weight = loss_fn.head.weight
            
            weight = weight.float()
            
            if weight.dim() == 3:
                weight_norm = F.normalize(weight, dim=2)
                features_norm = F.normalize(features, dim=1)
                cosine_all = torch.einsum('bd,ckd->bck', features_norm, weight_norm)
                logits, _ = cosine_all.max(dim=2)
            else:
                weight_norm = F.normalize(weight, dim=1)
                features_norm = F.normalize(features, dim=1)
                logits = features_norm @ weight_norm.t()
            
            test_preds.extend(logits.argmax(dim=1).cpu().numpy())
            test_labels_list.extend(labels.cpu().numpy())
    
    test_preds = np.array(test_preds)
    test_labels_arr = np.array(test_labels_list)
    
    test_acc = accuracy_score(test_labels_arr, test_preds)
    test_f1 = f1_score(test_labels_arr, test_preds, average='macro')
    f1_per_class = f1_score(test_labels_arr, test_preds, average=None, zero_division=0)
    
    if verbose:
        print(f"\n  TEST: Acc={test_acc*100:.2f}% | Macro-F1={test_f1*100:.2f}%")
        for i, f1 in enumerate(f1_per_class):
            print(f"    {id2label[i]}: {f1*100:.1f}%")
        sys.stdout.flush()
    
    # Clear GPU memory after experiment
    del model, loss_fn, optimizer
    clear_gpu_memory()
    
    return {
        'experiment_name': experiment_name, 'loss_type': loss_type, 'backbone_type': backbone_type,
        'best_epoch': best_epoch, 'best_val_f1': best_val_f1, 'test_accuracy': test_acc,
        'test_f1': test_f1, 'test_f1_per_class': f1_per_class.tolist(), 'loss_kwargs': loss_kwargs
    }


