def build_backbone(backbone_type: str, checkpoint_path: str = None, freeze_layers: int = 0,
                   hf_token: str = None, local_dir: str = None):
    if backbone_type == 'ctranspath':
        backbone = CTransPathBackbone(checkpoint_path, freeze_layers)
    elif backbone_type == 'uni2':
        backbone = UNI2Backbone(local_dir=local_dir, freeze_layers=freeze_layers, hf_token=hf_token)
    elif backbone_type == 'phikon':
        backbone = PhikonBackbone(checkpoint_path, freeze_layers)
    elif backbone_type == 'conch':
        backbone = CONCHBackbone(checkpoint_path, freeze_layers)
    else:
        raise ValueError(f"Unknown backbone: {backbone_type}")
    return backbone, backbone.out_features


def build_model_with_loss(loss_type: str, backbone_type: str, num_classes: int, 
                          embed_dim: int, checkpoint_path: str, freeze_layers: int = 0,
                          class_counts: List[int] = None, device: str = 'cuda',
                          ce_weight: torch.Tensor = None, total_epochs: int = 150,
                          hf_token: str = None, local_dir: str = None,
                          **loss_kwargs):
    backbone, backbone_dim = build_backbone(
        backbone_type, checkpoint_path, freeze_layers, 
        hf_token=hf_token, local_dir=local_dir
    )
    
    head = nn.Sequential(
        nn.Linear(backbone_dim, embed_dim),
        nn.LayerNorm(embed_dim),
        nn.GELU(),
        nn.Dropout(0.15),
    )
    model = nn.Sequential(backbone, head)
    
    s = loss_kwargs.get('s', 30.0)
    m = loss_kwargs.get('m', 0.5)
    tau = loss_kwargs.get('tau', 0.5)
    label_smoothing = loss_kwargs.get('label_smoothing', 0.1)
    use_focal = loss_kwargs.get('use_focal', True)
    focal_gamma = loss_kwargs.get('focal_gamma', 2.0)
    num_subcenters = loss_kwargs.get('num_subcenters', 3)
    
    if loss_type == 'fuzzyarcloss_v3_subcenters':
        loss_fn = FuzzyArcLossV3SubCenters(embed_dim, num_classes, s=s, m=m, tau=tau, num_subcenters=num_subcenters,
                                           label_smoothing=label_smoothing, ce_weight=ce_weight, use_focal=use_focal)
    elif loss_type == 'contrastive_fuzzyarc':
        alpha = loss_kwargs.get('alpha', 0.7)
        beta = loss_kwargs.get('beta', 0.3)
        supcon_temp = loss_kwargs.get('supcon_temperature', 0.07)
        loss_fn = ContrastiveFuzzyArcLoss(embed_dim, num_classes, s=s, m=m, tau=tau, num_subcenters=num_subcenters,
                                          label_smoothing=label_smoothing, ce_weight=ce_weight, use_focal=use_focal,
                                          alpha=alpha, beta=beta, supcon_temperature=supcon_temp)
    elif loss_type == 'evo_fuzzyarc':
        class_K = loss_kwargs.get('class_K', [5, 3, 5, 2, 3, 3])
        loss_fn = EvoFuzzyArcLoss(embed_dim, num_classes, s=s, m=m, tau=tau, class_K=class_K,
                                  label_smoothing=label_smoothing, ce_weight=ce_weight, use_focal=use_focal)
    elif loss_type == 'curriculum_fuzzyarc':
        m_min = loss_kwargs.get('m_min', 0.2)
        m_max = loss_kwargs.get('m_max', 0.5)
        loss_fn = CurriculumFuzzyArcLoss(embed_dim, num_classes, s=s, m_min=m_min, m_max=m_max, tau=tau,
                                         num_subcenters=num_subcenters, total_epochs=total_epochs,
                                         label_smoothing=label_smoothing, ce_weight=ce_weight, use_focal=use_focal)
    elif loss_type == 'ensemble_multihead':
        diversity_weight = loss_kwargs.get('diversity_weight', 0.1)
        loss_fn = EnsembleMultiHeadFuzzyArc(embed_dim, num_classes, label_smoothing=label_smoothing,
                                            ce_weight=ce_weight, use_focal=use_focal, diversity_weight=diversity_weight)
    else:
        raise ValueError(f"Unknown loss type: {loss_type}")
    
    return model, loss_fn


