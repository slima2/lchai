class CurriculumFuzzyArcMarginProduct(nn.Module):
    """Curriculum FuzzyArcLoss with progressive margin scheduling."""
    def __init__(self, in_features: int, out_features: int, 
                 s: float = 30.0, m_min: float = 0.2, m_max: float = 0.5,
                 tau: float = 0.5, num_subcenters: int = 3,
                 total_epochs: int = 150, easy_margin: bool = False):
        super().__init__()
        self.in_features = in_features
        self.out_features = out_features
        self.s = s
        self.m_min = m_min
        self.m_max = m_max
        self.tau = tau
        self.K = num_subcenters
        self.total_epochs = total_epochs
        self.easy_margin = easy_margin
        self.current_epoch = 0
        
        self.register_buffer('class_difficulty', torch.tensor([1.0, 0.6, 1.0, 0.0, 0.2, 0.3]))
        
        self.weight = nn.Parameter(torch.FloatTensor(out_features, num_subcenters, in_features))
        nn.init.xavier_uniform_(self.weight.view(out_features * num_subcenters, in_features))
        self.weight.data = self.weight.data.view(out_features, num_subcenters, in_features)
    
    def get_current_margin(self) -> float:
        progress = self.current_epoch / self.total_epochs
        return self.m_min + (self.m_max - self.m_min) * (1 - math.cos(math.pi * progress)) / 2
    
    def get_class_weights(self) -> torch.Tensor:
        progress = self.current_epoch / self.total_epochs
        if progress < 0.2:
            weights = torch.ones(self.out_features, device=self.class_difficulty.device)
        elif progress < 0.5:
            weights = 1.0 - 0.5 * self.class_difficulty
        else:
            weights = 0.5 + 0.5 * self.class_difficulty
        return weights
        
    def forward(self, features: torch.Tensor, labels: torch.Tensor) -> torch.Tensor:
        features = features.float()
        weight = self.weight.float()
        
        features_norm = F.normalize(features, dim=1)
        weight_norm = F.normalize(weight, dim=2)
        
        cosine_all = torch.einsum('bd,ckd->bck', features_norm, weight_norm)
        cosine, _ = cosine_all.max(dim=2)
        cosine = cosine.clamp(-1 + 1e-7, 1 - 1e-7)
        
        m = self.get_current_margin()
        cos_m = math.cos(m)
        sin_m = math.sin(m)
        th = math.cos(math.pi - m)
        mm = math.sin(math.pi - m) * m
        
        sine = torch.sqrt(1.0 - cosine ** 2 + 1e-7)
        phi = cosine * cos_m - sine * sin_m
        
        if self.easy_margin:
            phi = torch.where(cosine > 0, phi, cosine)
        else:
            phi = torch.where(cosine > th, phi, cosine - mm)
        
        batch_size = features.size(0)
        target_cosine = cosine[torch.arange(batch_size, device=features.device), labels]
        
        mu = torch.where(
            torch.abs(target_cosine) >= self.tau,
            0.8 + 0.2 * torch.abs(target_cosine),
            0.3 + 0.4 * torch.abs(target_cosine)
        )
        mu = mu.clamp(0, 1)
        
        one_hot = torch.zeros_like(cosine)
        one_hot.scatter_(1, labels.view(-1, 1), 1)
        
        mu_expanded = mu.unsqueeze(1)
        target_logits = mu_expanded * phi + (1 - mu_expanded) * cosine
        output = one_hot * target_logits + (1 - one_hot) * cosine
        
        return self.s * output


class CurriculumFuzzyArcLoss(nn.Module):
    """Curriculum FuzzyArcLoss with progressive training."""
    def __init__(self, in_features: int, out_features: int,
                 s: float = 30.0, m_min: float = 0.2, m_max: float = 0.5,
                 tau: float = 0.5, num_subcenters: int = 3,
                 total_epochs: int = 150,
                 label_smoothing: float = 0.1, ce_weight: torch.Tensor = None,
                 use_focal: bool = True, focal_gamma: float = 2.0):
        super().__init__()
        
        self.head = CurriculumFuzzyArcMarginProduct(
            in_features, out_features, s=s, m_min=m_min, m_max=m_max,
            tau=tau, num_subcenters=num_subcenters, total_epochs=total_epochs
        )
        self.ce = LabelSmoothingCrossEntropy(smoothing=label_smoothing, weight=ce_weight)
        self.use_focal = use_focal
        if use_focal:
            self.focal = FocalLoss(gamma=focal_gamma, weight=ce_weight)
        self.s = s
        self.weight = self.head.weight
    
    def set_epoch(self, epoch: int):
        self.head.current_epoch = epoch
    
    def forward(self, features: torch.Tensor, labels: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        logits = self.head(features, labels)
        
        class_weights = self.head.get_class_weights()
        sample_weights = class_weights[labels]
        
        log_probs = F.log_softmax(logits, dim=1)
        ce_loss = F.nll_loss(log_probs, labels, reduction='none')
        ce_loss = (ce_loss * sample_weights).mean()
        
        if self.use_focal:
            focal_loss = self.focal(logits, labels)
            loss = 0.6 * ce_loss + 0.4 * focal_loss
        else:
            loss = ce_loss
        
        return loss, logits


