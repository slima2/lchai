IMG_EXTS = {".png", ".jpg", ".jpeg", ".tif", ".tiff"}
MAT_EXCLUDE = {"__header__", "__version__", "__globals__"}


def pair_images_with_masks(image_dir: str, mask_dir: str) -> pd.DataFrame:
    records = []
    for fname in os.listdir(image_dir):
        stem, ext = os.path.splitext(fname)
        if ext.lower() not in IMG_EXTS:
            continue
        img_path = os.path.join(image_dir, fname)
        mask_path = None
        for mext in ['.mat', '.png', '.jpg', '.tif']:
            candidate = os.path.join(mask_dir, stem + mext)
            if os.path.exists(candidate):
                mask_path = candidate
                break
        if mask_path:
            records.append({'image_path': img_path, 'mask_path': mask_path, 'stem': stem})
    return pd.DataFrame(records)


def load_mask(mask_path: str, thresh: float = 0.5) -> np.ndarray:
    ext = os.path.splitext(mask_path)[1].lower()
    if ext == '.mat':
        mat = loadmat(mask_path)
        for key in mat:
            if key not in MAT_EXCLUDE:
                arr = mat[key]
                if isinstance(arr, np.ndarray) and arr.ndim >= 2:
                    return (arr > thresh).astype(np.uint8)
    else:
        img = Image.open(mask_path).convert('L')
        arr = np.array(img) / 255.0
        return (arr > thresh).astype(np.uint8)
    return None


class StainAugmentation:
    """Stain augmentation for H&E images."""
    def __init__(self, prob: float = 0.5):
        self.prob = prob
    
    def __call__(self, img):
        if random.random() > self.prob:
            return img
        
        img_np = np.array(img).astype(np.float32)
        h_shift = random.uniform(-0.08, 0.08)
        e_shift = random.uniform(-0.08, 0.08)
        
        img_np[:, :, 0] = np.clip(img_np[:, :, 0] * (1 + e_shift), 0, 255)
        img_np[:, :, 2] = np.clip(img_np[:, :, 2] * (1 + h_shift), 0, 255)
        
        brightness = random.uniform(0.92, 1.08)
        contrast = random.uniform(0.92, 1.08)
        img_np = np.clip((img_np - 128) * contrast + 128 * brightness, 0, 255)
        
        return Image.fromarray(img_np.astype(np.uint8))


class HistDataset(Dataset):
    """Histopathology dataset."""
    def __init__(self, df: pd.DataFrame, label_col: str, label2id: Dict,
                 img_size: int = 224, aug: bool = True,
                 use_roi_crop: bool = True, roi_padding: int = 24,
                 mask_thresh: float = 0.5,
                 use_stain_aug: bool = True, stain_aug_prob: float = 0.5):
        self.df = df.reset_index(drop=True)
        self.label_col = label_col
        self.label2id = label2id
        self.img_size = img_size
        self.aug = aug
        self.use_roi_crop = use_roi_crop
        self.roi_padding = roi_padding
        self.mask_thresh = mask_thresh
        
        if aug:
            self.stain_aug = StainAugmentation(prob=stain_aug_prob) if use_stain_aug else None
            self.transform = T.Compose([
                T.RandomHorizontalFlip(),
                T.RandomVerticalFlip(),
                T.RandomRotation(30),
                T.RandomAffine(degrees=0, translate=(0.1, 0.1), scale=(0.9, 1.1)),
                T.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.15),
                T.RandomGrayscale(p=0.05),
                T.GaussianBlur(kernel_size=3, sigma=(0.1, 1.0)),
                T.Resize((img_size, img_size)),
                T.ToTensor(),
                T.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225]),
                T.RandomErasing(p=0.1, scale=(0.02, 0.1)),
            ])
        else:
            self.stain_aug = None
            self.transform = T.Compose([
                T.Resize((img_size, img_size)),
                T.ToTensor(),
                T.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
            ])
    
    def __len__(self):
        return len(self.df)
    
    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        img = Image.open(row['image_path']).convert('RGB')
        
        if self.use_roi_crop and 'mask_path' in row:
            mask = load_mask(row['mask_path'], self.mask_thresh)
            if mask is not None:
                ys, xs = np.where(mask > 0)
                if len(xs) > 0:
                    x1, x2 = xs.min(), xs.max()
                    y1, y2 = ys.min(), ys.max()
                    h, w = mask.shape
                    x1, y1 = max(0, x1 - self.roi_padding), max(0, y1 - self.roi_padding)
                    x2, y2 = min(w, x2 + self.roi_padding), min(h, y2 + self.roi_padding)
                    img = img.crop((x1, y1, x2, y2))
        
        if self.stain_aug is not None:
            img = self.stain_aug(img)
        
        img = self.transform(img)
        label = self.label2id[str(row[self.label_col])]
        return img, label


def mixup_data(x, y, alpha=0.4):
    lam = np.random.beta(alpha, alpha) if alpha > 0 else 1
    batch_size = x.size(0)
    index = torch.randperm(batch_size).to(x.device)
    mixed_x = lam * x + (1 - lam) * x[index]
    return mixed_x, y, y[index], lam


def cutmix_data(x, y, alpha=1.0):
    lam = np.random.beta(alpha, alpha) if alpha > 0 else 1
    batch_size = x.size(0)
    index = torch.randperm(batch_size).to(x.device)
    
    W, H = x.size(2), x.size(3)
    cut_rat = np.sqrt(1 - lam)
    cut_w, cut_h = int(W * cut_rat), int(H * cut_rat)
    cx, cy = np.random.randint(W), np.random.randint(H)
    
    bbx1, bby1 = np.clip(cx - cut_w // 2, 0, W), np.clip(cy - cut_h // 2, 0, H)
    bbx2, bby2 = np.clip(cx + cut_w // 2, 0, W), np.clip(cy + cut_h // 2, 0, H)
    
    x[:, :, bbx1:bbx2, bby1:bby2] = x[index, :, bbx1:bbx2, bby1:bby2]
    lam = 1 - ((bbx2 - bbx1) * (bby2 - bby1) / (W * H))
    return x, y, y[index], lam


